"use strict";

// commitlint.config.cjs・stylelint.config.cjsと同様、参照側リポジトリへsymlinkでそのまま
// 配布する共有textlint設定（sync-manifest.json参照）。プロダクト固有のカスタマイズは
// 想定しておらず、textlint-rule-preset-ja-technical-writingをベースにそのまま使う（issue #433）。
module.exports = {
  rules: {
    "preset-ja-technical-writing": {
      // 本リポジトリのドキュメントは、issue/PR番号や過去の経緯を伴う因果関係の説明を
      // 1文に埋め込む文体を意図的に採用しており（本リポジトリの`.github/workflows/*.yml`の
      // コメント・各`docs/*.md`で一貫）、この文体では1文が100文字を大きく超えることが
      // 常態化している（実測値は最大555文字）。無理に短文化すると、括弧書きで補足している
      // 背景・理由の対応関係が崩れ、かえって読みにくくなるため、この規約では無効化する
      "sentence-length": false,
      // 上記と同じ長い複文の文体に起因して、1文中に同じ助詞（が・に・で・は等）が
      // 複数回登場するケースが多数を占め（実測値54件）、いずれも文を分割しない限り
      // 解消できない。sentence-lengthを無効化した以上、文分割を前提とするこのルールも
      // 実質的に機能しないため、同じ理由で無効化する
      "no-doubled-joshi": false,
      // 同じく長文の文体では読点（、）が4つ以上・カンマが4つ以上になる文が
      // 多数を占め、これも文分割を前提とするルールのため同じ理由で無効化する
      "max-ten": false,
      "max-comma": false,
      // 本リポジトリの各ドキュメントは全体を通じて常体（「〜する。」等の辞書形終止）で
      // 統一されており、「です」「ます」で終わる文は実測で0件だった。にもかかわらず、
      // 明示的な「である。」止めの文が1〜数件でもあると、このルールは文書全体を
      // ですます調と誤判定し、その「である。」文を逆に指摘する（実測10件、いずれも
      // 対象ファイルの「ですます」実測数は0件）。辞書形終止をですます調の根拠として
      // 数えられない実装上の制約により、常体オンリーの文書では機能しないため無効化する
      "no-mix-dearu-desumasu": false,
    },
  },
};
